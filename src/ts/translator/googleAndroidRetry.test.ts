beforeEach(()=>{vi.resetModules();vi.useFakeTimers();vi.setSystemTime(100000);vi.spyOn(navigator,'userAgent','get').mockReturnValue('RisuBardAndroid/test')})
afterEach(()=>{vi.useRealTimers();vi.restoreAllMocks();vi.unstubAllGlobals()})
test.each(['429','network','invalid-json','empty'])('a transient %s fallback never poisons the retry cache',async failure=>{
 const fetcher=vi.fn().mockImplementationOnce(async()=>{if(failure==='network')throw Error('offline');return new Response(failure==='invalid-json'?'not json':failure==='empty'?'[]':'{}',{status:failure==='429'?429:200})}).mockImplementation(async()=>new Response(JSON.stringify([[['번역문']]])))
 vi.stubGlobal('fetch',fetcher)
 const {translate}=await import('./translator')
 expect(await translate('source text',false)).toBe('source text')
 await vi.advanceTimersByTimeAsync(61000)
 expect(await translate('source text',false)).toBe('번역문')
 expect(await translate('source text',false)).toBe('번역문')
 expect(fetcher).toHaveBeenCalledTimes(2)
})
test('desktop retains the existing direct fetch failure behavior',async()=>{
 vi.spyOn(navigator,'userAgent','get').mockReturnValue('desktop')
 vi.stubGlobal('fetch',vi.fn().mockRejectedValue(new Error('network error')))
 const {translate}=await import('./translator')
 await expect(translate('desktop sample',false)).rejects.toThrow('network error')
})

test.each(['empty','missing','invalid'])('desktop keeps upstream %s response behavior',async shape=>{
 vi.spyOn(navigator,'userAgent','get').mockReturnValue('desktop')
 vi.stubGlobal('fetch',vi.fn(async()=>new Response(JSON.stringify(shape==='empty'?[[]]:shape==='missing'?[]:[{}]))))
 const {translate}=await import('./translator')
 if(shape==='invalid') await expect(translate('desktop shape',false)).rejects.toThrow()
 else expect(await translate('desktop shape',false)).toBe('desktop shape')
})
